-- phase: expand
-- An agent's change can wait for its maker's OK (plan §AD.15: "an agent's edit can wait for approval (a per-space
-- setting)"). With agent_review on, what the person's agent writes is kept as a proposal, not written: the editor shows
-- what it would add, change and remove, and the maker applies it (it becomes a version) or discards it. The last five
-- proposals of a space are kept.
ALTER TABLE space_apps ADD COLUMN IF NOT EXISTS agent_review boolean NOT NULL DEFAULT false;
CREATE TABLE IF NOT EXISTS space_app_proposals (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    space_id    text COLLATE "C" NOT NULL REFERENCES space_apps(id) ON DELETE CASCADE,
    files       text NOT NULL,
    by_subject  text COLLATE "C",
    by_name     text,
    note        text,
    created_at  bigint NOT NULL
);
CREATE INDEX IF NOT EXISTS space_app_proposals_space ON space_app_proposals (space_id, id DESC);
